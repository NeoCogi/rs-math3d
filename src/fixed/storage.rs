//! Sealed storage and format capabilities. Format lists are generated by a
//! recursive macro so invalid widths fail at the type boundary, including raw
//! construction and `Default`, rather than waiting for an arithmetic operation.

use core::{fmt::Debug, hash::Hash};

/// Prevents external storage implementations from violating widening invariants.
mod sealed {
    /// Only the four built-in signed storage widths can implement this marker.
    pub trait Sealed {}
    impl Sealed for i8 {}
    impl Sealed for i16 {}
    impl Sealed for i32 {}
    impl Sealed for i64 {}
}

/// A signed storage integer whose product fits in `i128`.
///
/// This trait is sealed. Use `i8`, `i16`, `i32`, or `i64`; representation
/// conversions always check range before narrowing.
pub trait Repr: sealed::Sealed + Copy + Default + Debug + Eq + Ord + Hash {
    /// Storage width, including its sign bit.
    const BITS: u32;
    /// Smallest stored integer, widened without changing its value.
    const MIN: i128;
    /// Largest stored integer, widened without changing its value.
    const MAX: i128;
    /// Stored zero, used by constant construction.
    const ZERO: Self;
    /// Stored one, representing one quantum rather than numeric one.
    const UNIT: Self;
    /// Widens the stored integer exactly.
    fn widen(self) -> i128;
    /// Narrows only when the stored integer is representable.
    fn narrow(value: i128) -> Option<Self>;
}

/// A valid signed binary format with `FRAC < Repr::BITS`.
///
/// Implementations are sealed through [`Repr`]. All arithmetic and raw access
/// require this bound, so an invalid format cannot be constructed safely.
pub trait Format<const FRAC: u32>: Repr {}

/// A format that can represent positive one, required by `num_traits::Num`.
pub trait UnitFormat<const FRAC: u32>: Format<FRAC> {
    /// Exact numeric one in the storage representation.
    const ONE_BITS: Self;
}

/// A format that can represent two, required by the crate's `Scalar` contract.
pub trait ScalarFormat<const FRAC: u32>: UnitFormat<FRAC> {}

/// A scalar format with at least two fractional bits for exact half/quarter.
pub trait RealFormat<const FRAC: u32>: ScalarFormat<FRAC> {}

/// Implements every format up to a storage width's last magnitude bit.
macro_rules! formats {
    ($r:ty; $($f:literal),*) => { $(impl Format<$f> for $r {})* };
}

/// Implements positive-one formats without requiring const-expression bounds.
macro_rules! unit_formats {
    ($r:ty; $($f:literal),*) => { $(impl UnitFormat<$f> for $r {
        const ONE_BITS: Self = 1 << $f;
    })* };
}

/// Implements the constant-two capability for an enumerated format range.
macro_rules! scalar_formats {
    ($r:ty; $($f:literal),*) => { $(impl ScalarFormat<$f> for $r {})* };
}

/// Implements the analytic capability for an enumerated format range.
macro_rules! real_formats {
    ($r:ty; $($f:literal),*) => { $(impl RealFormat<$f> for $r {})* };
}

/// Supplies exact checked widening/narrowing for a built-in signed integer.
macro_rules! repr {
    ($($r:ty),*) => { $(impl Repr for $r {
        const BITS: u32 = <$r>::BITS;
        const MIN: i128 = <$r>::MIN as i128;
        const MAX: i128 = <$r>::MAX as i128;
        const ZERO: Self = 0;
        const UNIT: Self = 1;
        fn widen(self) -> i128 { self as i128 }
        fn narrow(value: i128) -> Option<Self> {
            if value < <Self as Repr>::MIN || value > <Self as Repr>::MAX {
                None
            } else { Some(value as Self) }
        }
    })* };
}

