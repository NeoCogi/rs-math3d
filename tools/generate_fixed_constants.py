from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from pathlib import Path


def atan(x):
    """Compute atan(x) for |x| < 1 to the active Decimal context precision."""
    total = term = x
    n = 1
    while True:
        term *= -(x * x)
        candidate = total + term / (2 * n + 1)
        if candidate == total:
            return total
        total = candidate
        n += 1


with localcontext() as context:
    context.prec = 120
    pi = 16 * atan(Decimal(1) / 5) - 4 * atan(Decimal(1) / 239)
    angles = [pi / 4] + [atan(Decimal(2) ** -i) for i in range(1, 97)]
    gain = Decimal(1)
    for i in range(97):
        gain /= (1 + Decimal(2) ** (-2 * i)).sqrt()

    def quantize(value, fractional=96):
        """Round a real constant once to its exact binary integer encoding."""
        return int((value * (Decimal(2) ** fractional)).to_integral_value(rounding=ROUND_HALF_EVEN))

    output = [
        *Path('src/lib.rs').read_text().split('//! # rs-math3d')[0].rstrip().splitlines(),
        '',
        '//! Generated by `tools/generate_fixed_constants.py`; do not edit by hand.',
        '//! Constants use Q96 unless their name explicitly specifies another scale.',
        '',
        '/// Pi with 96 fractional bits.',
        f'pub(super) const PI: i128 = {quantize(pi)};',
        '/// Tau with 64 fractional bits for bounded full-range input reduction.',
        f'pub(super) const TAU_Q64: i128 = {quantize(2 * pi, 64)};',
        '/// Reciprocal CORDIC gain after all table iterations.',
        f'pub(super) const GAIN: i128 = {quantize(gain)};',
        '/// atan(2^-i) in radians for rotation and vectoring iterations.',
        'pub(super) const ANGLES: [i128; 97] = [',
    ]
    output += [f'    {quantize(angle)},' for angle in angles]
    output += ['];', '']
    gain64 = Decimal(1)
    for i in range(61):
        gain64 /= (1 + Decimal(2) ** (-2 * i)).sqrt()
    output += [
        '/// Pi with 60 fractional bits for the experimental i64 path.',
        f'pub(super) const PI_Q60: i64 = {quantize(pi, 60)};',
        '/// Reciprocal gain for 61 steps; shorter schedules differ by less than 2^-64.',
        f'pub(super) const GAIN_Q60: i64 = {quantize(gain64, 60)};',
        '/// atan(2^-i) with 60 fractional bits, rescaled at compile time.',
        'pub(super) const ANGLES_Q60: [i64; 61] = [',
    ]
    output += [f'    {quantize(angle, 60)},' for angle in angles[:61]]
    output += ['];', '']
    Path('src/fixed/constants.rs').write_text('\n'.join(output))

    def sin_cos(value):
        """Independent Taylor reference after high-precision range reduction."""
        value %= 2 * pi
        if value > pi:
            value -= 2 * pi
        sine = sin_term = value
        cosine = cos_term = Decimal(1)
        n = 1
        while True:
            sin_term *= -value * value / ((2 * n) * (2 * n + 1))
            cos_term *= -value * value / ((2 * n - 1) * (2 * n))
            next_sine = sine + sin_term
            next_cosine = cosine + cos_term
            if next_sine == sine and next_cosine == cosine:
                return sine, cosine
            sine, cosine = next_sine, next_cosine
            n += 1

    notice = Path('src/lib.rs').read_text().split('//! # rs-math3d')[0].rstrip().replace('//', '#')
    references = [notice, '# Independent Decimal references: FRAC,raw,sin_raw,cos_raw']
    for fractional in (2, 8, 16, 32, 61):
        scale = Decimal(2) ** fractional
        raws = [-(2**63), -(2**63)+1, -1234567890123456789, -1, 0, 1, 1234567890123456789, 2**63-2, 2**63-1]
        for raw in raws:
            sine, cosine = sin_cos(Decimal(raw) / scale)
            references.append(','.join(map(str, (fractional, raw, quantize(sine, fractional), quantize(cosine, fractional)))))
    Path('src/fixed/reference.csv').write_text('\n'.join(references)+'\n')

    def atan_positive(value):
        """Independent half-angle reduction keeps the atan series away from one."""
        if value > 1:
            return pi / 2 - atan_positive(1 / value)
        doublings = 0
        while value > Decimal('0.25'):
            value /= 1 + (1 + value * value).sqrt()
            doublings += 1
        return atan(value) * (2 ** doublings)

    def acos(value):
        """Independent Decimal acos via sqrt and reduced atan, without CORDIC."""
        if value == 1:
            return Decimal(0)
        if value == -1:
            return pi
        if value == 0:
            return pi / 2
        angle = atan_positive((1 - value * value).sqrt() / abs(value))
        return pi - angle if value < 0 else angle

    experiment = [notice, '# Decimal 120-digit reference: storage,frac,op,input_raw,nearest_raw,residual_raw']

    def record(bits, fractional, operation, raw, value):
        """Split the reference into an exact integer and a bounded residual.

        This retains sub-quantum error resolution even when a raw output is too
        large for f64 to preserve its low integer bits. Consumers subtract the
        integers before converting the small difference to a floating metric.
        """
        scaled = value * (Decimal(2) ** fractional)
        nearest = int(scaled.to_integral_value(rounding=ROUND_HALF_EVEN))
        residual = scaled - nearest
        experiment.append(f'{bits},{fractional},{operation},{raw},{nearest},{residual:.36E}')

    state = 0x123456789abcdef
    for bits, fractional in ((32, 8), (32, 16), (32, 29), (64, 16), (64, 32), (64, 44), (64, 48)):
        scale = Decimal(2) ** fractional
        minimum, maximum = -(2 ** (bits - 1)), 2 ** (bits - 1) - 1
        raw_angles = {0, -1, 1}
        raw_angles.update(minimum + i for i in range(32))
        raw_angles.update(maximum - i for i in range(32))
        for _ in range(256):
            state = (state * 6364136223846793005 + 1442695040888963407) % (2 ** 64)
            raw_angles.add(minimum + (state >> (64 - bits)))
        # Quarter-turn neighborhoods expose axis folding and tangent amplification
        # at both small angles and the largest representable angle magnitudes.
        max_turn = int(Decimal(maximum) / (scale * pi / 2))
        for turns in (0, 1, -1, 2, -2, 3, 1001, max_turn, -max_turn):
            base = int((turns * pi / 2 * scale).to_integral_value(rounding=ROUND_HALF_EVEN))
            raw_angles.update(base + offset for offset in range(-3, 4) if minimum <= base + offset <= maximum)
        for raw in sorted(raw_angles):
            sine, cosine = sin_cos(Decimal(raw) / scale)
            record(bits, fractional, 'sin', raw, sine)
            record(bits, fractional, 'cos', raw, cosine)
            record(bits, fractional, 'tan', raw, sine / cosine)
        raw_acos = {0, -1, 1}
        for i in range(17):
            raw_acos.update((-int(scale) + i, int(scale) - i))
        for _ in range(128):
            state = (state * 6364136223846793005 + 1442695040888963407) % (2 ** 64)
            raw_acos.add(-int(scale) + state % (2 * int(scale) + 1))
        for raw in sorted(raw_acos):
            record(bits, fractional, 'acos', raw, acos(Decimal(raw) / scale))
    Path('src/fixed/cordic_reference.csv').write_text('\n'.join(experiment)+'\n')
