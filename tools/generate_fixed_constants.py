from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from pathlib import Path


def atan(x):
    """Compute atan(x) for |x| < 1 to the active Decimal context precision."""
    total = term = x
    n = 1
    while True:
        term *= -(x * x)
        candidate = total + term / (2 * n + 1)
        if candidate == total:
            return total
        total = candidate
        n += 1


with localcontext() as context:
    context.prec = 120
    pi = 16 * atan(Decimal(1) / 5) - 4 * atan(Decimal(1) / 239)
    angles = [pi / 4] + [atan(Decimal(2) ** -i) for i in range(1, 97)]
    gain = Decimal(1)
    for i in range(97):
        gain /= (1 + Decimal(2) ** (-2 * i)).sqrt()

    def quantize(value, fractional=96):
        """Round a real constant once to its exact binary integer encoding."""
        return int((value * (Decimal(2) ** fractional)).to_integral_value(rounding=ROUND_HALF_EVEN))

    output = [
        *Path('src/lib.rs').read_text().split('//! # rs-math3d')[0].rstrip().splitlines(),
        '',
        '//! Generated by `tools/generate_fixed_constants.py`; do not edit by hand.',
        '//! All constants use Q96 unless their name explicitly says Q64.',
        '',
        '/// Pi with 96 fractional bits.',
        f'pub(super) const PI: i128 = {quantize(pi)};',
        '/// Tau with 64 fractional bits for bounded full-range input reduction.',
        f'pub(super) const TAU_Q64: i128 = {quantize(2 * pi, 64)};',
        '/// Reciprocal CORDIC gain after all table iterations.',
        f'pub(super) const GAIN: i128 = {quantize(gain)};',
        '/// atan(2^-i) in radians for rotation and vectoring iterations.',
        'pub(super) const ANGLES: [i128; 97] = [',
    ]
    output += [f'    {quantize(angle)},' for angle in angles]
    output += ['];', '']
    Path('src/fixed/constants.rs').write_text('\n'.join(output))

    def sin_cos(value):
        """Independent Taylor reference after high-precision range reduction."""
        value %= 2 * pi
        if value > pi:
            value -= 2 * pi
        sine = sin_term = value
        cosine = cos_term = Decimal(1)
        n = 1
        while True:
            sin_term *= -value * value / ((2 * n) * (2 * n + 1))
            cos_term *= -value * value / ((2 * n - 1) * (2 * n))
            next_sine = sine + sin_term
            next_cosine = cosine + cos_term
            if next_sine == sine and next_cosine == cosine:
                return sine, cosine
            sine, cosine = next_sine, next_cosine
            n += 1

    notice = Path('src/lib.rs').read_text().split('//! # rs-math3d')[0].rstrip().replace('//', '#')
    references = [notice, '# Independent Decimal references: FRAC,raw,sin_raw,cos_raw']
    for fractional in (2, 8, 16, 32, 61):
        scale = Decimal(2) ** fractional
        raws = [-(2**63), -(2**63)+1, -1234567890123456789, -1, 0, 1, 1234567890123456789, 2**63-2, 2**63-1]
        for raw in raws:
            sine, cosine = sin_cos(Decimal(raw) / scale)
            references.append(','.join(map(str, (fractional, raw, quantize(sine, fractional), quantize(cosine, fractional)))))
    Path('src/fixed/reference.csv').write_text('\n'.join(references)+'\n')
